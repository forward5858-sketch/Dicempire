const rulesCache={};
function pluralForm(lang,n){
  try{return (rulesCache[lang]||(rulesCache[lang]=new Intl.PluralRules(lang))).select(n);}catch(e){return n===1?"one":"other";}
}
/* Anahtarın metnini verilen dilde döndürür; o dilde yoksa İngilizce, o da yoksa Türkçe, hiçbiri yoksa anahtarın kendisi */
function translate(lang,key,params){
  const p=params||{};
  let l=lang,v=DICT[l]&&DICT[l][key];
  if(v===undefined){l=FALLBACK;v=DICT[l][key];}
  if(v===undefined){l="tr";v=DICT[l][key];}
  if(v===undefined)return key;
  if(typeof v==="object")v=v[pluralForm(l,+p.n||0)]??v.other;
  return v.replace(/\{(\w+)\}/g,(m,k)=>k in p?String(p[k]):m);
}
/* Kayıtlı tercih varsa o, yoksa tarayıcının dil listesinden ilk desteklenen, o da yoksa İngilizce */
function detect(saved,prefs){
  if(saved&&DICT[saved])return saved;
  for(const pref of prefs||[]){
    const base=String(pref).toLowerCase().split(/[-_]/)[0];
    if(DICT[base])return base;
  }
  return FALLBACK;
}

